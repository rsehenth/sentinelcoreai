    private static readonly Dictionary<string, string> english = Build();

    public static string English(string portuguese) => english.TryGetValue(portuguese, out var value) ? value : portuguese;

    public static ResourceDictionary CreateDictionary(AppLanguage language)
    {
        var dictionary = new ResourceDictionary();
        for (var index = 0; index < Entries.Length; index++)
            dictionary[$"T{index}"] = language == AppLanguage.Portuguese ? Entries[index].Pt : Entries[index].En;
        return dictionary;
    }

    private static Dictionary<string, string> Build()
    {
        var map = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var entry in Entries) map[entry.Pt] = entry.En;
        return map;
    }
